"""Convert Zephyr's CFB fonts (DroidSansMono, Apache-2.0) to row-major bitmaps.

Usage: scripts/gen_fonts.py <zephyr>/subsys/fb/cfb_fonts.c > bootloader/src/display/fonts.c
       scripts/gen_fonts.py --preview <cfb_fonts.c> 1016 "Ab%"
"""
import re
import sys

FONTS = {"1016": (10, 16), "1524": (15, 24), "2032": (20, 32)}
# Characters kept per font (the 20x32 font only draws the percentage).
RANGES = {"1016": (32, 126), "1524": (32, 126), "2032": (37, 57)}
FIRST, LAST = 32, 126


def parse(src):
    out = {}
    for name, (w, h) in FONTS.items():
        m = re.search(r"cfb_font_%s\[95\]\[\d+\] = \{(.*?)\n\};" % name, src, re.S)
        glyphs = re.findall(r"\{([^{}]*)\}", m.group(1))
        assert len(glyphs) == 95, (name, len(glyphs))
        rows_all = []
        for g in glyphs:
            data = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]{2}", g)]
            assert len(data) == w * h // 8, (name, len(data))
            rows = []
            for y in range(h):
                bits = 0
                for x in range(w):
                    byte = data[x * (h // 8) + y // 8]  # column-major, LSB = top
                    if byte >> (y % 8) & 1:
                        bits |= 1 << (w - 1 - x)
                rows.append(bits)
            rows_all.append(rows)
        out[name] = rows_all
    return out


def emit(fonts):
    print("/*\n * Generated by scripts/gen_fonts.py from Zephyr's subsys/fb/cfb_fonts.c.")
    print(" * Glyphs: DroidSansMono, Copyright (C) 2008 The Android Open Source Project,")
    print(" * Licensed under the Apache License, Version 2.0.\n */\n")
    print('#include "fonts.h"\n')
    for name, (w, h) in FONTS.items():
        stride = (w + 7) // 8
        lo, hi = RANGES[name]
        sel = list(enumerate(fonts[name]))[lo - FIRST:hi - FIRST + 1]
        print("static const uint8_t glyphs_%s[%d][%d] = {" % (name, hi - lo + 1, stride * h))
        for i, rows in sel:
            b = []
            for r in rows:
                v = r << (stride * 8 - w)  # left-align, MSB = leftmost pixel
                b += [(v >> (8 * (stride - 1 - k))) & 0xFF for k in range(stride)]
            ch = chr(FIRST + i)
            print("\t/* %s */ {%s}," % (repr(ch), ", ".join("0x%02x" % x for x in b)))
        print("};\n")
        # Ink bounds per glyph for proportional spacing: {first ink column, ink width}.
        print("static const uint8_t metrics_%s[%d][2] = {" % (name, hi - lo + 1))
        for i, rows in sel:
            ink = 0
            for r in rows:
                ink |= r
            cols = [x for x in range(w) if ink >> (w - 1 - x) & 1]
            if cols:
                print("\t{%d, %d}," % (cols[0], cols[-1] - cols[0] + 1))
            else:
                print("\t{0, %d}," % max(2, w * 2 // 5))  # space
        print("};\n")
        print("const struct font font_%s = {.w = %d, .h = %d, .stride = %d, .first = %d,"
              " .last = %d, .track = %d, .bits = &glyphs_%s[0][0], .metrics = metrics_%s};\n"
              % (name, w, h, stride, lo, hi, max(1, w // 8), name, name))


def preview(fonts, name, text):
    w, h = FONTS[name]
    for y in range(h):
        line = ""
        for ch in text:
            r = fonts[name][ord(ch) - FIRST][y]
            line += "".join("#" if r >> (w - 1 - x) & 1 else "." for x in range(w)) + " "
        print(line)


if __name__ == "__main__":
    if sys.argv[1] == "--preview":
        preview(parse(open(sys.argv[2]).read()), sys.argv[3], sys.argv[4])
    else:
        emit(parse(open(sys.argv[1]).read()))
